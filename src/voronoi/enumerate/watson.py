"""Watson code enumeration for cells with kissing number s = n.

Per DSEKM19 §2.2: every well-rounded lattice (Λ, m(Λ)) with s = n in
dim n corresponds, after a unimodular change of basis, to a sublattice
extension Λ ⊃ Λ' = Z^n parameterized by a Z/dZ-code c ∈ Z^n where
d = [Λ : Λ']. The code is determined up to the action of signed
permutations of coordinates (the "B_n action") which corresponds to
unimodular automorphisms of Λ' = Z^n that permute the basis.

References:
    [DSEKM19] arXiv:1910.11598 §2.2 "Watson's index theory and very
              small cells".
    [DSEKM19] Table 2: orbit counts by index for n ≤ 9.
"""

from __future__ import annotations

from voronoi.cells import VoronoiCell


def enumerate_index_1_cells(n: int) -> list[VoronoiCell]:
    """Index-1 cells in Z^n with s = n.

    There is exactly one such cell: the lattice is Λ = Z^n itself,
    with min vectors ±e_i. The cell is the convex hull of the n rank-1
    forms ê_i = e_i e_i^T inside Sym²(R^n).

    Args:
        n: lattice rank (= cell dimension since s = n).

    Returns:
        A list of one :class:`VoronoiCell` whose min-vector matrix is
        the n × n identity.
    """
    if n < 1:
        raise ValueError(f"n must be >= 1, got {n}")
    rows = tuple(tuple(1 if i == j else 0 for j in range(n)) for i in range(n))
    return [VoronoiCell(lattice_rank=n, dim=n, min_vectors=rows)]


def _watson_min_vectors_d2_canonical(n: int, weight: int) -> list[list[int]]:
    """Min-vector matrix for the d=2 cell with canonical binary code of
    weight ``weight``.

    The canonical S_n-orbit rep of a weight-w binary code is
    c = (1, ..., 1, 0, ..., 0) with w leading 1s. The Watson lattice
    Λ_c = Z^n + (c/2) Z is generated by

        b_0 = c/2,       b_i = e_i for i = 1, ..., n-1.

    Setting B' = (b_0, ..., b_{n-1}) as the new basis (so b_i ↦ e_i in
    new coords), the min vectors of (Λ_c, std inner product) become:

        m_0 = e_0 (old) = 2 b_0 - sum_{i ∈ supp \\ {0}} b_i
                       = (2, -1, ..., -1, 0, ..., 0)  [w-1 -1s, then 0s]
        m_i = e_i (old) = b_i = (0, ..., 0, 1, 0, ..., 0)  for i ≥ 1.

    These are the rows of M.

    Min vectors are ±e_i (in old coords). For w >= 5 the extension
    element c/2 has norm w/4 > 1, so it's strictly above the min and
    s(Λ_c) = n exactly. (For w = 4 the extension hits norm 1, giving
    s > n — excluded from the index-2 s=n classification.)
    """
    if weight < 5 or weight > n:
        raise ValueError(
            f"weight must be in [5, {n}] for n={n} cells, got {weight}"
        )
    M: list[list[int]] = []
    # m_0 = (2, -1, ..., -1 [w-1 entries], 0, ..., 0).
    m_0 = [0] * n
    m_0[0] = 2
    for i in range(1, weight):
        m_0[i] = -1
    M.append(m_0)
    # m_i = e_i for i = 1, ..., n-1 (in new coords).
    for i in range(1, n):
        row = [0] * n
        row[i] = 1
        M.append(row)
    return M


def enumerate_index_2_cells(n: int) -> list[VoronoiCell]:
    """Index-2 cells in Z^n with s = n via binary Watson codes.

    Per [DSEKM19] §2.2 + Table 2, codes of weight w ∈ {5, ..., n}
    parameterize the cells. Mod the S_n action on coordinates there's
    exactly one representative per weight, so for n=8 we get 4 cells
    (w ∈ {5, 6, 7, 8}).

    Args:
        n: lattice rank (= cell dimension).

    Returns:
        List of :class:`VoronoiCell` instances, one per weight in
        ``range(5, n + 1)``. Empty when ``n < 5``.
    """
    if n < 1:
        raise ValueError(f"n must be >= 1, got {n}")
    if n < 5:
        return []
    cells: list[VoronoiCell] = []
    for w in range(5, n + 1):
        rows = _watson_min_vectors_d2_canonical(n, w)
        cells.append(VoronoiCell.from_rows(rows))
    return cells


def _watson_min_vectors_d_canonical(
    n: int, weight: int, d: int
) -> list[list[int]]:
    """Min-vector matrix for the d-cyclic cell with canonical
    "all-ones-on-support" Z/dZ code of given weight.

    For canonical c = (1, ..., 1, 0, ..., 0) with w leading 1s, take
    basis B' = (c/d, e_1, ..., e_{n-1}) of Λ_c = Z^n + (c/d) Z. In new
    coords:

        m_0 = e_0 (old) = d·b_0 − Σ_{i ∈ supp(c) \\ {0}} b_i
                       = (d, -1, ..., -1, 0, ..., 0)  [w-1 -1s, then 0s]
        m_i = e_i (old) = b_i for i ≥ 1.

    The Watson constraint for s = n exactly is ∑|a_i| > 2d strict
    (equality gives extras at the same min norm — see d=2 weight 4
    case). For all-ones canonical codes that's weight > 2d, so
    weight ≥ 2d + 1.

    This handles cyclic Z/dZ extensions where the canonical orbit rep
    (mod signed permutation symmetry) is the all-ones-on-support
    pattern. For d ≥ 4 with non-coprime entries (e.g. a_i = 2 in Z/4Z)
    this construction does NOT cover all orbits — see d=4 enumerator.
    """
    if d < 2:
        raise ValueError(f"d must be >= 2 for cyclic case, got {d}")
    if weight <= 2 * d:
        raise ValueError(
            f"weight must be > 2d = {2*d} for s=n, got {weight}"
        )
    if weight > n:
        raise ValueError(f"weight must be <= n = {n}, got {weight}")
    M: list[list[int]] = []
    # m_0 = (d, -1, ..., -1, 0, ..., 0).
    m_0 = [0] * n
    m_0[0] = d
    for i in range(1, weight):
        m_0[i] = -1
    M.append(m_0)
    for i in range(1, n):
        row = [0] * n
        row[i] = 1
        M.append(row)
    return M


def enumerate_index_3_cells(n: int) -> list[VoronoiCell]:
    """Index-3 cells in Z^n with s = n via Z/3Z Watson codes.

    Z/3Z codes have entries a_i ∈ {0, 1, 2}, with 2 ≡ -1 mod 3. Mod
    signed permutations of coordinates (S_n × {±1}^n), all nonzero
    entries can be normalized to 1, so the canonical orbit rep is the
    all-ones-on-support code (1, ..., 1, 0, ..., 0). The strict Watson
    constraint ∑|a_i| > 2d = 6 forces weight ≥ 7. Per [DSEKM19] Table 2,
    for n=8 we get 2 cells (weights 7 and 8).
    """
    if n < 1:
        raise ValueError(f"n must be >= 1, got {n}")
    if n < 7:
        return []
    cells: list[VoronoiCell] = []
    for w in range(7, n + 1):
        rows = _watson_min_vectors_d_canonical(n, w, d=3)
        cells.append(VoronoiCell.from_rows(rows))
    return cells


def _watson_min_vectors_d_cyclic_canonical(
    n: int, n_2: int, n_1: int, n_0: int, d: int
) -> list[list[int]]:
    """Min-vector matrix for a d-cyclic cell with canonical Z/dZ code
    of given composition (n_2 twos, n_1 ones, n_0 zeros).

    Canonical placement (mod S_n × {±1}^n): 2's first, then 1's, then 0's:

        c = (2, ..., 2, 1, ..., 1, 0, ..., 0)
              n_2 times  n_1 times  n_0 times

    For ``[Λ:Z^n] = d`` strict (cyclic), we need n_1 >= 1 (at least one
    entry coprime to d). The construction generalizes the d=2 / d=3
    canonical: drop e_p where p = n_2 (first c_p=1 position) and use

        B' = (c/d, e_0, ..., e_{p-1}, e_{p+1}, ..., e_{n-1})

    as the new basis. In new coords:

        e_k (k != p):  index k+1 if k<p else k, value 1.
        e_p (k == p):  (d, -c_0, -c_1, ..., -c_{p-1}, -c_{p+1}, ..., -c_{n-1})
                       (with the c_i's renumbered to skip p).

    Used for d ∈ {4, 5} where canonical entries are {0, 1, 2} after
    sign normalization. (For d=2 / d=3 the simpler all-ones-on-support
    helper suffices since 2 ≡ -1 in Z/3 and 1 = -1 in Z/2.)
    """
    if d < 2:
        raise ValueError(f"d must be >= 2, got {d}")
    if n != n_2 + n_1 + n_0:
        raise ValueError(
            f"composition (n_2={n_2}, n_1={n_1}, n_0={n_0}) sums to "
            f"{n_2+n_1+n_0}, expected {n}"
        )
    if n_1 < 1:
        raise ValueError(
            f"n_1 >= 1 required for primitive d={d} cyclic cell"
        )
    weight = 2 * n_2 + n_1
    if weight <= 2 * d:
        raise ValueError(
            f"weight = 2 n_2 + n_1 = {weight}, must be > 2d = {2*d}"
        )

    c = [2] * n_2 + [1] * n_1 + [0] * n_0
    p = n_2

    M: list[list[int]] = []
    for k in range(n):
        new_coords = [0] * n
        if k == p:
            new_coords[0] = d
            for i in range(n):
                if i == p:
                    continue
                new_idx = i + 1 if i < p else i
                new_coords[new_idx] = -c[i]
        else:
            new_idx = k + 1 if k < p else k
            new_coords[new_idx] = 1
        M.append(new_coords)
    return M


def _watson_min_vectors_d4_cyclic_canonical(
    n: int, n_2: int, n_1: int, n_0: int
) -> list[list[int]]:
    """Backwards-compat alias for the d=4 case of
    :func:`_watson_min_vectors_d_cyclic_canonical`."""
    return _watson_min_vectors_d_cyclic_canonical(n, n_2, n_1, n_0, d=4)


def _gram_centroid(cell: VoronoiCell) -> list[list[int]]:
    """Centroid Gram form A_σ = Σ_v v v^T = M^T M (rows = min vectors)."""
    n = cell.lattice_rank
    g = [[0] * n for _ in range(n)]
    for v in cell.min_vectors:
        for i in range(n):
            for j in range(n):
                g[i][j] += v[i] * v[j]
    return g


def enumerate_index_4_cyclic_cells(n: int) -> list[VoronoiCell]:
    """Index-4 cyclic cells in Z^n with s = n via Z/4Z Watson codes.

    For n=8, [DSEKM19] Table 2 says 4 cells. We enumerate every
    composition (n_2, n_1, n_0) with n_2 + n_1 + n_0 = n, n_1 >= 1
    (primitive), and weight 2 n_2 + n_1 > 8 (strict Watson). The
    Watson constraint is necessary but not sufficient for s = n
    exactly — most compositions yield a candidate where the Watson
    code has subtle extras at min norm (s > n cells in some
    coordinate-permuted basis), which DSEKM Table 2 does NOT classify
    as (n, n) cells.

    Filter: ``noether.api.lattice.is_realizable_min_vector_set`` —
    the [DSEKM19] §3.1 LP loop only accepts V's that are exactly the
    tight min set of some PD form (no equal-norm extras). On n=8,
    this drops 12 of 16 candidates leaving exactly 4 cells.

    Then qfisom on centroid Grams confirms these 4 are pairwise
    inequivalent.
    """
    if n < 1:
        raise ValueError(f"n must be >= 1, got {n}")
    if n < 5:
        return []

    from noether.api.lattice import is_realizable_min_vector_set, isometry

    candidates: list[VoronoiCell] = []
    for n_2 in range(0, n + 1):
        for n_1 in range(1, n + 1 - n_2):
            n_0 = n - n_2 - n_1
            weight = 2 * n_2 + n_1
            if weight <= 2 * 4:
                continue
            try:
                rows = _watson_min_vectors_d4_cyclic_canonical(n, n_2, n_1, n_0)
                candidates.append(VoronoiCell.from_rows(rows))
            except ValueError:
                continue

    realizable_candidates: list[VoronoiCell] = []
    for cand in candidates:
        V = [list(v) for v in cand.min_vectors]
        try:
            ok = is_realizable_min_vector_set(V, max_iterations=200)
        except RuntimeError:
            # Convergence failure on this candidate — treat as not
            # realizable (this is the s > n case where the LP loop
            # doesn't terminate cleanly).
            ok = False
        if ok:
            realizable_candidates.append(cand)

    distinct: list[VoronoiCell] = []
    distinct_grams: list[list[list[int]]] = []
    for cand in realizable_candidates:
        cand_gram = _gram_centroid(cand)
        is_new = True
        for d_gram in distinct_grams:
            if isometry(cand_gram, d_gram) is not None:
                is_new = False
                break
        if is_new:
            distinct.append(cand)
            distinct_grams.append(cand_gram)
    return distinct


def enumerate_index_5_cells(n: int) -> list[VoronoiCell]:
    """Index-5 cells in Z^n with s = n via Z/5Z Watson codes.

    Same composition-based construction as d=4 cyclic, but with d=5.
    Canonical Z/5Z entries (mod sign-flip) are {0, 1, 2} since 2 and
    3 = -2 mod 5 are not equal (and |3| as Z/5 element = 2 =|2|).

    Watson constraint: weight 2 n_2 + n_1 > 2d = 10. For n=8 this gives
    9 candidate compositions (e.g. (3, 5, 0) at weight 11, (4, 4, 0) at
    12, etc.). After realizability + qfisom filtering, [DSEKM19] Table 2
    says 1 cell.
    """
    if n < 1:
        raise ValueError(f"n must be >= 1, got {n}")
