"""Watson enumeration and coverage-certified Voronoi census stages.

Watson index theory (DSEKM19 §2.2) parameterizes cells with kissing
number s = n by codes over Z/dZ where d = [Λ : Λ'] is the index of the
sublattice generated by min vectors. For (N=8, n=8), DSEKM Table 2
gives 13 orbits split across indices d ∈ {1, 2, 3, 4, 2², 5}.

This package enumerates cells per index and validates against the
published orbit database. Current rank-eight counts are:

    d=1: 1 cell    (this module)
    d=2: 4 cells
    d=3: 2 cells
    d=4: 4 cells
    d=2²: 1 cell
    d=5: 1 cell
    -----
    13 cells total (target).
"""

