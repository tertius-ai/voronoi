def enumerate_all_n_eq_N_cells(n: int) -> list:
    """Exhaust the verified rank-eight Watson base, with 13 exact orbits.

    The implemented index families are exhaustive only for ``n=8``. For other
    ranks use the individual index enumerators as partial constructions; their
    union is not a certificate of complete base-layer coverage.
    """
    if n != 8:
        raise ValueError("exhaustive Watson enumeration is supported only for n=8")
    return (
        enumerate_index_1_cells(n)
        + enumerate_index_2_cells(n)
        + enumerate_index_3_cells(n)
        + enumerate_index_4_cyclic_cells(n)
        + enumerate_index_4_klein_cells(n)
        + enumerate_index_5_cells(n)
    )


